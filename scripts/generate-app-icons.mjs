import sharp from 'sharp'
import { readFileSync, mkdirSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'
import { exec } from 'child_process'
import { promisify } from 'util'

const execAsync = promisify(exec)
const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const buildDir = join(__dirname, '..', 'electron', 'build')

// SVGファイルを読み込む
const svgBuffer = readFileSync(join(buildDir, 'icon.svg'))

console.log('🎨 Generating application icons...\n')

// 1024x1024のPNG (macOS用のベース)
await sharp(svgBuffer)
  .resize(1024, 1024)
  .png()
  .toFile(join(buildDir, 'icon-1024.png'))

console.log('✓ Generated icon-1024.png (1024x1024)')

// 512x512のPNG (Windows用のベース)
await sharp(svgBuffer)
  .resize(512, 512)
  .png()
  .toFile(join(buildDir, 'icon.png'))

console.log('✓ Generated icon.png (512x512)')

// 256x256のPNG
await sharp(svgBuffer)
  .resize(256, 256)
  .png()
  .toFile(join(buildDir, 'icon-256.png'))

console.log('✓ Generated icon-256.png (256x256)')

// .icns generation for macOS (requires iconutil on macOS)
if (process.platform === 'darwin') {
  console.log('\n📱 Generating .icns file for macOS...')
  try {
    const iconsetDir = join(buildDir, 'icon.iconset')
    mkdirSync(iconsetDir, { recursive: true })

    // Generate all required sizes for macOS iconset
    const sizes = [16, 32, 64, 128, 256, 512, 1024]
    for (const size of sizes) {
      await sharp(svgBuffer)
        .resize(size, size)
        .png()
        .toFile(join(iconsetDir, `icon_${size}x${size}.png`))

      if (size <= 512) {
        // 2x retina version
        await sharp(svgBuffer)
          .resize(size * 2, size * 2)
          .png()
          .toFile(join(iconsetDir, `icon_${size}x${size}@2x.png`))
      }
    }

    // Convert to .icns using iconutil
    await execAsync(`iconutil -c icns "${iconsetDir}" -o "${join(buildDir, 'icon.icns')}"`)
    console.log('✓ Generated icon.icns')

    // Clean up iconset
    await execAsync(`rm -rf "${iconsetDir}"`)
  } catch (error) {
    console.log('⚠ Could not generate .icns (iconutil not available)')
    console.log('  .icns will be generated during build on macOS')
  }
}

// .ico generation for Windows
console.log('\n💻 Generating .ico file for Windows...')
// Note: electron-builder will generate this automatically from icon.png
console.log('✓ icon.png ready (electron-builder will generate .ico)')

console.log('\n✨ App icon generation complete!')
console.log('Note: .icns and .ico will be generated by electron-builder during build')
